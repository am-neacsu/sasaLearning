import express from 'express';
import cookieParser from 'cookie-parser';
import rateLimit from 'express-rate-limit';
import cors from 'cors';
import helmet from 'helmet';
import morgan from 'morgan';
import { env } from './config/env.js';
import healthRouter from './routes/health.js';
import authRouter from './routes/auth.js';
import profileRouter from './routes/profile.js';
import catalogRouter from './routes/catalog.js';
import dashboardRouter from './routes/dashboard.js';
import progressRouter from './routes/progress.js';
import practiceRouter from './routes/practice.js';
import questionsRouter from './routes/questions.js';
import homeworkRouter from './routes/homework.js';
import homeworkResultsRouter from './routes/homeworkResults.js';
import achievementsRouter from './routes/achievements.js';
import importRouter from './routes/import.js';
import parentRouter from './routes/parent.js';
import parentResultsRouter from './routes/parentResults.js';
import parentInsightsRouter from './routes/parentInsights.js';
import childrenRouter from './routes/children.js';
const app = express();
app.use(helmet());
app.use(cors({ origin: env.CLIENT_URL, credentials: true }));
app.use(express.json({ limit: '1mb' }));
app.use(cookieParser());
app.use('/api/auth/login', rateLimit({ windowMs: 15 * 60 * 1000, limit: 20, standardHeaders: true, legacyHeaders: false }));
app.set('trust proxy', 1);
app.use(morgan(env.NODE_ENV === 'production' ? 'combined' : 'dev'));
app.get('/api', (_req,res) => res.json({ name: 'Learning Platform API', version: '0.1.0' }));
app.use('/api/health', healthRouter);
app.use('/api/auth', authRouter);
app.use('/api/profile', profileRouter);
app.use('/api/catalog', catalogRouter);
app.use('/api/dashboard', dashboardRouter);
app.use('/api/progress', progressRouter);
app.use('/api/practice', practiceRouter);
app.use('/api/questions', questionsRouter);
app.use('/api/homework', homeworkRouter);
app.use('/api/homework', homeworkResultsRouter);
app.use('/api/achievements', achievementsRouter);
app.use('/api/import', importRouter);
app.use('/api/parent', parentRouter);
app.use('/api/parent', parentResultsRouter);
app.use('/api/parent', parentInsightsRouter);
app.use('/api/children', childrenRouter);
app.use((err, _req, res, _next) => { console.error(err); res.status(500).json({ error: 'An unexpected server error occurred.', ...(env.NODE_ENV === 'development' ? { detail: err.message } : {}) }); });
app.listen(env.PORT, () => console.log(`API listening on http://localhost:${env.PORT}`));
